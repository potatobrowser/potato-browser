// Prints the Homebrew cask for the release described by a latest.json (see release-manifest.mjs).
// The release workflow writes it to Casks/potato-browser.rb in potatobrowser/homebrew-tap.
// Usage: node scripts/homebrew-cask.mjs release/latest.json [owner/repo]
import fs from 'node:fs';

const [file, repo = process.env.GITHUB_REPOSITORY || 'potatobrowser/potato-browser'] = process.argv.slice(2);
if (!file) throw new Error('usage: homebrew-cask.mjs <latest.json> [owner/repo]');
const m = JSON.parse(fs.readFileSync(file, 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(m.version)) throw new Error(`bad version ${m.version}`);
for (const a of ['arm64', 'x64']) {
  if (!/^[0-9a-f]{64}$/.test(m.sha256?.[a] ?? '')) throw new Error(`bad sha256 for ${a}`);
  if (m.files?.[a] !== `Potato-Browser-${m.version}-${a}.dmg`) throw new Error(`unexpected file name for ${a}: ${m.files?.[a]}`);
}

process.stdout.write(`# Generated by ${repo}/apps/browser/scripts/homebrew-cask.mjs on each release. Do not edit by hand.
cask "potato-browser" do
  arch arm: "arm64", intel: "x64"

  version "${m.version}"
  sha256 arm:   "${m.sha256.arm64}",
         intel: "${m.sha256.x64}"

  url "https://github.com/${repo}/releases/download/v#{version}/Potato-Browser-#{version}-#{arch}.dmg"
  name "Potato Browser"
  desc "Chromium-based browser that hides the AI features of websites"
  homepage "https://potatobrowser.com/"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: :ventura

  app "Potato Browser.app"

  zap trash: [
    "~/Library/Application Support/Potato Browser",
    "~/Library/Caches/com.potatobrowser.app",
    "~/Library/Caches/Potato Browser",
    "~/Library/HTTPStorages/com.potatobrowser.app",
    "~/Library/Logs/Potato Browser",
    "~/Library/Preferences/com.potatobrowser.app.plist",
    "~/Library/Saved Application State/com.potatobrowser.app.savedState",
  ]
end
`);
